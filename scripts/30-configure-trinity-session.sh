#!/usr/bin/env bash
# 30-configure-trinity-session.sh — make Trinity launchable three ways:
#   1. display manager login (lightdm; tdm evaluated separately)
#   2. startx from console
#   3. raw xinit fallback
# Run AS ROOT (prlctl exec) after 20-install-trinity-core.sh.
#
# Safe: backs up any file it replaces; writes nothing outside listed paths.
set -euo pipefail
log() { printf '[%s] %s\n' "$(date +%H:%M:%S)" "$*"; }
die() { log "FATAL: $*"; exit 1; }
backup() { [ -f "$1" ] && cp -n "$1" "$1.bak.tde" && log "backed up $1" || true; }

[ "$(id -u)" -eq 0 ] || die "must run as root"

# ---- locate starttde ------------------------------------------------------
STARTTDE=""
for c in /opt/trinity/bin/starttde /usr/bin/starttde; do
    [ -x "$c" ] && STARTTDE="$c" && break
done
[ -n "$STARTTDE" ] || die "starttde not found — is trinity-tdebase installed?"
log "starttde: $STARTTDE"

# ---- 1. xsession entry for display managers -------------------------------
# The tdebase RPM may ship its own entry; only create ours if none exists.
mkdir -p /usr/share/xsessions
if ls /usr/share/xsessions/*.desktop 2>/dev/null | xargs grep -sl "starttde" >/dev/null 2>&1; then
    log "xsession entry already present: $(ls /usr/share/xsessions/*.desktop | xargs grep -sl starttde)"
else
    backup /usr/share/xsessions/trinity.desktop
    cat > /usr/share/xsessions/trinity.desktop <<EOF
[Desktop Entry]
Encoding=UTF-8
Name=Trinity
Comment=Trinity Desktop Environment (TDE R14)
Exec=$STARTTDE
TryExec=$STARTTDE
Type=XSession
EOF
    log "wrote /usr/share/xsessions/trinity.desktop"
fi

# ---- 2. display manager: lightdm ------------------------------------------
# Rationale (docs/session-startup.md): first milestone favours a small,
# well-supported DM; tdm can replace it later once the session is proven.
dnf -y install lightdm lightdm-gtk
systemctl enable lightdm.service >/dev/null 2>&1 || true
systemctl set-default graphical.target
log "lightdm enabled; default target = graphical"

# ---- 3. startx / xinit fallback for user trinity --------------------------
XINITRC=/home/trinity/.xinitrc
if [ -f "$XINITRC" ] && ! grep -q starttde "$XINITRC"; then backup "$XINITRC"; fi
cat > "$XINITRC" <<EOF
#!/bin/sh
# generated by 30-configure-trinity-session.sh — starts Trinity via startx
exec $STARTTDE
EOF
chown trinity:trinity "$XINITRC"; chmod +x "$XINITRC"
log "wrote $XINITRC (startx now launches Trinity for user trinity)"

log "Session configuration complete. Reboot (or systemctl isolate graphical.target) to test DM path."
